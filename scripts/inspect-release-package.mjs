import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url)),host=process.env.ASTERLYN_HOST_CHECKOUT;
if(!host&&!process.env.ASTERLYN_PLUGIN_INSPECTOR)throw Error('Set ASTERLYN_HOST_CHECKOUT or ASTERLYN_PLUGIN_INSPECTOR to use the canonical native admission validator');
const summary=JSON.parse(await readFile(join(root,'release/release-summary.json'),'utf8')),manifest=JSON.parse(await readFile(join(root,'manifest.json'),'utf8'));
if(summary.asset!==`${manifest.id}-${manifest.version}.asterlyn-plugin.tgz`)throw Error('Unexpected release asset identity');
const asset=join(root,'release',summary.asset),bytes=await readFile(asset);
if(bytes.length!==summary.bytes||createHash('sha256').update(bytes).digest('hex')!==summary.sha256)throw Error('Release package digest mismatch');
const version=process.env.ASTERLYN_HOST_VERSION??JSON.parse(await readFile(join(host,'package.json'),'utf8')).version;
const args=[asset,manifest.distribution.repository,manifest.version,version];
const native=process.env.ASTERLYN_PLUGIN_INSPECTOR;
const result=spawnSync(native??'cargo',native?args:['run','--quiet','--locked','--manifest-path',join(resolve(host),'Cargo.toml'),'-p','asterlyn-plugin-package','--bin','asterlyn-plugin-inspect','--',...args],{encoding:'utf8'});
if(result.error)throw result.error;if(result.status!==0)throw Error(`Canonical admission failed: ${result.stderr.slice(-4000)}`);
console.log(JSON.stringify({asset:summary.asset,sha256:summary.sha256,bytes:bytes.length,hostVersion:version,canonicalAdmission:true}));
